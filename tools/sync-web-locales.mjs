#!/usr/bin/env node
// Copies biletflow_web's KK/RU/EN dictionaries into src/locales/*.js so the mobile app uses the
// web's exact wording. Read-only for the web repo. Re-run after the web locales change:
//   node tools/sync-web-locales.mjs [path/to/biletflow_web]
import { readFileSync, writeFileSync, rmSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";

const web = resolve(process.argv[2] || "../biletflow_web");
for (const lang of ["en", "ru", "kk"]) {
  const src = join(web, "frontend/src/i18n/locales", `${lang}.json`);
  const data = JSON.parse(readFileSync(src, "utf8"));
  writeFileSync(`src/locales/${lang}.js`,
    `// Generated by tools/sync-web-locales.mjs from biletflow_web/frontend/src/i18n/locales/${lang}.json. Do not edit.\n` +
    `export default ${JSON.stringify(data, null, 2)};\n`);
  if (existsSync(`src/locales/${lang}.json`)) rmSync(`src/locales/${lang}.json`);
  console.log(`src/locales/${lang}.js <- ${src}`);
}
